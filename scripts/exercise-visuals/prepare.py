#!/usr/bin/env python3
"""Package imagegen's pose sheets into local 3.2-second WebP loops.

The artwork is created with the built-in imagegen tool. This script only
extracts the supplied cells, resizes them for the app, and encodes playback.
Original generated sheets remain under output/exercise-motion-sources/.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DEFINITIONS = json.loads((HERE / 'definitions.json').read_text())
ART = ROOT / 'mobile/assets/exercise-motions'
# 240px keeps list thumbnails sharp and roughly halves the bundled size.
SIZE = 240
SOURCES = ROOT / 'output/exercise-motion-sources'

BASE_PROMPT = '''Use case: scientific-educational.
Create ONE production animation sprite sheet for a fitness app exercise: {name} ({key}).
STYLE REFERENCE: provided image is ONLY a style reference. Match its elegant BLACK muscular adult male silhouette, warm IVORY anatomical contour lines, vivid RED working {muscles}. Anonymous face, no facial details. Recognizable dark grey equipment with ivory outlines. Output an actual RGBA transparent cutout: all empty space between the figures and inside apparatus is fully transparent, alpha zero. Do not paint a checkerboard, white, grey or black background. No text, tile numbers, borders, grid lines, arrows, scenery, glow, haze or shadows.
EXACT LAYOUT: SIXTEEN equal cells, FOUR columns by FOUR rows, no gutters. Prefer a 2048x2048 canvas. In every cell include the ENTIRE necessary figure and ALL equipment with a safe 8% margin. Never crop heads, limbs, apparatus or handles. Each cell has exactly the same framing, camera and scale. Do not let content cross cell boundaries.
CAMERA: fixed {view} view, no camera movement or zoom.
START POSE: {start}.
END POSE: {end}.
CRITICAL MOVEMENT / EQUIPMENT: {detail}
POSE ORDER: read left-to-right, then next row. Frames 1 through 8 progress from START to END in 8 evenly spaced actual joint/articulated-equipment poses. Frames 9 through 16 repeat those same poses in REVERSE order: end, 6/7, 5/7, 4/7, 3/7, 2/7, 1/7, start. First and last poses identical; middle two end poses identical. Only the joints and apparatus specified above move; fixed supports and floor contact points stay stationary. Preserve the same body proportions, face, hands, clothing, equipment shape and red muscle colors across every cell. The motion must be the actual exercise, never whole-image shaking or sliding.
'''


def requests():
    result = []
    for definition in DEFINITIONS:
        prompt = BASE_PROMPT.format(**definition)
        if definition.get('motion') == 'cycle':
            prompt = prompt[:prompt.index('POSE ORDER:')] + 'POSE ORDER: create 16 evenly spaced sequential phases of ONE continuous natural running stride cycle, beginning and ending at the same pose. Do not reverse the phases halfway. Keep the runner centered, with consistent proportions and equipment.\n'
        elif definition.get('motion') == 'hold':
            prompt = f'''Use case: scientific-educational.
Create ONE static fitness exercise illustration: {definition['name']}.
STYLE REFERENCE ONLY: match the provided black muscular adult male silhouette, ivory anatomical contour lines and vivid red {definition['muscles']}. Transparent alpha, no text, labels, grid, shadows, arrows or background.
Use a fixed {definition['view']} view. Show the ENTIRE figure with safe margins.
POSE: {definition['start']}.
CRITICAL: {definition['detail']}
Do not create a grid or multiple figures. One single polished illustration.
'''
        result.append({'key': definition['key'], 'name': definition['name'], 'prompt': prompt})
    SOURCES.mkdir(parents=True, exist_ok=True)
    (SOURCES / 'requests.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    public = [{key: definition[key] for key in ('key', 'name', 'aliases', 'group')} | {'animated': definition.get('motion') != 'hold'} for definition in DEFINITIONS]
    (ROOT / 'mobile/src/data/exercise-visuals.json').write_text(json.dumps(public, ensure_ascii=False, indent=2) + '\n')
    lines = ["// Generated by scripts/exercise-visuals/prepare.py --requests.", "// Static requires keep every illustration bundled for offline use.", "export const exerciseVisualAssets: Record<string, { animation: number; poster: number }> = {"]
    for definition in DEFINITIONS:
        key = definition['key']
        animation = f"require('../assets/exercise-motions/{key}.webp')" if definition.get('motion') != 'hold' else f"require('../assets/exercise-motions/{key}-poster.webp')"
        lines.append(f"  '{key}': {{ animation: {animation}, poster: require('../assets/exercise-motions/{key}-poster.webp') }},")
    lines.append('};')
    (ROOT / 'mobile/src/exercise-visual-assets.ts').write_text('\n'.join(lines) + '\n')
    print(json.dumps({'requests': len(result), 'requestFile': str(SOURCES / 'requests.json')}))


def package(key, source, ffmpeg):
    definition = next(item for item in DEFINITIONS if item['key'] == key)
    ART.mkdir(parents=True, exist_ok=True)
    SOURCES.mkdir(parents=True, exist_ok=True)
    original = SOURCES / f'{key}.png'
    if source.resolve() != original.resolve():
        shutil.copy2(source, original)
    with Image.open(original) as image:
        width, height = image.size
        if image.mode != 'RGBA' or image.getextrema()[3][0] != 0:
            raise ValueError(f'{key}: source must have real transparent alpha')
    common = [ffmpeg, '-hide_banner', '-loglevel', 'error', '-y', '-filter_threads', '1']
    poster = ART / f'{key}-poster.webp'
    still = ['-c:v', 'libwebp', '-lossless', '0', '-q:v', '82']
    if definition.get('motion') == 'hold':
        subprocess.run(common + ['-i', str(original), '-vf', f'scale={SIZE}:{SIZE}:force_original_aspect_ratio=decrease:flags=lanczos', '-frames:v', '1', *still, str(poster)], check=True)
    else:
        # Generated alpha-trimmed sheets need not have dimensions divisible by
        # four. Normalize the canvas uniformly before extracting equal cells.
        grid_width = round(width / 4) * 4
        grid_height = round(height / 4) * 4
        grid = f'scale={grid_width}:{grid_height}:flags=lanczos'
        crop = "crop=iw/4:ih/4:x='mod(n,4)*out_w':y='floor(mod(n,16)/4)*out_h'"
        resize = f'scale={SIZE}:{SIZE}:force_original_aspect_ratio=decrease:flags=lanczos'
        subprocess.run(common + ['-loop', '1', '-framerate', '5', '-i', str(original), '-vf', ','.join([grid, crop, resize]), '-frames:v', '16', '-c:v', 'libwebp_anim', '-lossless', '0', '-q:v', '70', '-compression_level', '4', '-loop', '0', str(ART / f'{key}.webp')], check=True)
        # A recognizable intermediate pose is also the reduced-motion fallback.
        poster_filter = ','.join([grid, 'crop=iw/4:ih/4:x=iw/4:y=ih/4', resize])
        subprocess.run(common + ['-i', str(original), '-vf', poster_filter, '-frames:v', '1', *still, str(poster)], check=True)
    metadata_dir = SOURCES / 'packaged'
    metadata_dir.mkdir(exist_ok=True)
    metadata = {'key': key, 'name': definition['name'], 'sourceSha256': hashlib.sha256(original.read_bytes()).hexdigest(), 'sourceSize': [width, height], 'animated': definition.get('motion') != 'hold', 'loopDurationMs': 3200 if definition.get('motion') != 'hold' else 0, 'posterBytes': poster.stat().st_size}
    if definition.get('motion') != 'hold':
        metadata['animationBytes'] = (ART / f'{key}.webp').stat().st_size
    (metadata_dir / f'{key}.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'packaged': len(list(metadata_dir.glob('*.json'))), **metadata}, ensure_ascii=False))


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--requests', action='store_true')
parser.add_argument('--key')
parser.add_argument('--source', type=Path)
parser.add_argument('--ffmpeg', default='ffmpeg')
args = parser.parse_args()
if args.requests:
    requests()
elif args.key and args.source:
    package(args.key, args.source, args.ffmpeg)
else:
    parser.error('Use --requests or --key KEY --source PNG')
